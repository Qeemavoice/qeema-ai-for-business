- قيمة فويس سوق عربي للتعليق الصوتي يربط المعلقين بالعملاء من الشركات والوكالات في الخليج والعالم العربي.
- لكل معلق «جواز صوت» برقم QV يعرّف صوته ولهجاته، وشارة «صوت بشري موثّق».
- الاستنساخ بالذكاء الاصطناعي اختياري تمامًا، ولا يتم إلا بعقد مكتوب يحدد: الموافقة، ونطاق الاستخدام، والمدة، ونسبة المعلق من كل استخدام لصوته المستنسخ، وحقه في سحب الموافقة.
- المعلق المستنسخ يكسب من الطلبات البشرية ومن استخدام نسخته الرقمية معًا، والعميل يسمع صوته على نصه فورًا فتزيد فرص حجزه.
- الاستنساخ يحتاج تسجيلًا نظيفًا من دقيقة إلى دقيقتين على الأقل، بصوت واحد، في مكان هادئ، وبنفس اللهجة والنبرة.
- النسب والأسعار والتفاصيل موضحة في الشروط وسياسة الاستخدام وفي عقد المعلق. لا تذكر أي نسبة أو مبلغ.

